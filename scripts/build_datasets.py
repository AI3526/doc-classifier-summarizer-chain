def clean(text: str) -> str:
    return re.sub(r"\s+", " ", unicodedata.normalize("NFKC", text)).strip()


def family_rows(topic: str, label: str, block: str) -> list[dict]:
    lines = [line.strip() for line in block.splitlines() if line.strip()]
    if len(lines) != 42:
        raise ValueError(f"{topic}/{label}: expected 42 families, got {len(lines)}")
    rows = []
    for n, line in enumerate(lines, start=1):
        variants = line.split("|")
        if len(variants) != 2:
            raise ValueError(f"Family {topic}/{label}/{n} must have two authored texts")
        split = "train" if n <= 30 else "validation" if n <= 36 else "test"
        group = f"{topic}-{label}-family-{n:02d}"
        for index, variant in enumerate(variants, start=1):
            rows.append({"id": f"{group}-v{index}", "text": clean(variant),
                         "label": label, "group_id": group, "source": SOURCE,
                         "split": split})
    return rows


