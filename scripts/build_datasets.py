def character_ngrams(text: str, size: int = 3) -> set[str]:
    text = re.sub(r"\s+", "", clean(text))
    return {text[i:i + size] for i in range(max(0, len(text) - size + 1))}


def similarity_candidates(rows: list[dict], threshold: float = 0.55) -> list[dict]:
    """Flag cross-split lexical similarities; a flag is NOT proof of leakage."""
    grams = [character_ngrams(row["text"]) for row in rows]
    pairs = []
    for i, left in enumerate(rows):
        for j in range(i + 1, len(rows)):
            right = rows[j]
            if left["split"] == right["split"]:
                continue
            union = grams[i] | grams[j]
            similarity = len(grams[i] & grams[j]) / len(union) if union else 0.0
            if similarity >= threshold:
                pairs.append({"left": left["id"], "right": right["id"],
                              "char_3gram_jaccard": round(similarity, 4)})
    return pairs


