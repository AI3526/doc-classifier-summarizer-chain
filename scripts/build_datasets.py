def build() -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    manifest: dict = {
        "dataset_version": VERSION,
        "authored_date": "2026-10-01",
        "language": "ko",
        "provenance": "Original LLM-authored fictional teaching scenarios; no customer export, private source, web scraping, or external API",
        "pii": "No real personal data. Fictional roles and abstract situations only.",
        "split_policy": "Immutable v1 family assignment: 01-30 train; 31-36 validation; 37-42 test. Both authored variants stay together. Generation families are separate.",
        "limitations": ["Synthetic scores do not prove real-world generalization.",
                        "Two views of one family are correlated; effective scenario count is half the classification row count.",
                        "Balanced labels and moderately clean Korean differ from production distributions.",
                        "Document classes have strong writing-style cues; the baseline classification score may exploit these shortcuts.",
                        "Scenario-family disjointness is not full semantic independence: shipping family 03 and family 37 share delivered-but-missing intent.",
                        "Shared institutional topics across document labels are intentional boundary examples.",
                        "Calibrated confidence is not guaranteed, and a closed-set classifier cannot establish out-of-domain safety."],
        "topics": {},
    }
    for topic in LABELS:
        directory = DATA / topic
        directory.mkdir(parents=True, exist_ok=True)
        rows = [row for label, block in SEEDS[topic].items() for row in family_rows(topic, label, block)]
        eval_rows = generation_rows(topic)
        assert len(eval_rows) == 24
        stats = {"splits": {}, "qa": check_rows(rows, eval_rows)}
        if topic == "documents":
            stats["writing_style_diagnostic"] = document_style_diagnostic(rows)
        write_json(directory / "labels.json", {"labels": list(LABELS[topic]), "descriptions": LABELS[topic]})
        for split in ("train", "validation", "test"):
            selected = [row for row in rows if row["split"] == split]
            write_csv(directory / f"{split}.csv", selected)
            stats["splits"][split] = {"rows": len(selected),
                                       "families": len({r["group_id"] for r in selected}),
                                       "labels": dict(Counter(r["label"] for r in selected))}
        smoke = [row for row in rows if row["split"] == "train" and int(row["group_id"].rsplit("-", 1)[1]) <= 3]
        assert {row["id"] for row in smoke} <= {row["id"] for row in rows if row["split"] == "train"}
        write_csv(directory / "smoke.csv", smoke)
        stats["splits"]["smoke"] = {"rows": len(smoke), "source": "train subset only", "labels": dict(Counter(r["label"] for r in smoke))}
        write_jsonl(directory / "generation_eval.jsonl", eval_rows)
        stats["splits"]["generation_eval"] = {"rows": len(eval_rows), "families": len(eval_rows),
                                                  "labels": dict(Counter(r["expected_label"] for r in eval_rows))}
        challenges = challenge_rows() if topic == "inquiries" else document_challenge_rows()
        assert len({row["id"] for row in challenges}) == len(challenges)
        assert not {row["id"] for row in challenges} & {row["id"] for row in rows + eval_rows}
        assert not {clean(row["text"]) for row in challenges} & {clean(row["text"]) for row in rows + eval_rows}
        write_jsonl(directory / "challenge.jsonl", challenges)
        stats["splits"]["challenge"] = {
            "rows": len(challenges),
            "purpose": "Separate robustness/OOD set; no closed-set label accuracy target" if topic == "inquiries"
                       else "Post-baseline style diagnostic exercise; not an untouched final test set"}
        stats["files"] = {path.name: {"sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "bytes": path.stat().st_size}
                          for path in sorted(directory.iterdir()) if path.is_file() and path.suffix in {".csv", ".json", ".jsonl"}}
        manifest["topics"][topic] = stats
    write_json(DATA / "manifest.json", manifest)
    print(json.dumps({topic: stats["splits"] for topic, stats in manifest["topics"].items()}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    build()
