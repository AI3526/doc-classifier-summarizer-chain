def generation_rows(topic: str) -> list[dict]:
    result = []
    for label in LABELS[topic]:
        for n, (text, required, forbidden) in enumerate(GENERATION_SPECS[topic][label], start=1):
            family = f"{topic}-{label}-generation-{n:02d}"
            result.append({"id": family, "text": text, "expected_label": label,
                           "required_points": required, "forbidden_claims": forbidden,
                           "group_id": family, "source": SOURCE, "split": "generation_eval",
                           "rubric_note": "의미 기준으로 사람이 평가합니다. 문자열 포함 여부만으로 정답 처리하지 않습니다."})
    return result


